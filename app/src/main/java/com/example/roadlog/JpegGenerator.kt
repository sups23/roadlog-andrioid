package com.example.roadlog

object JpegGenerator {
    private val HEADER = byteArrayOf(
        0xFF.toByte(), 0xD8.toByte(), 0xFF.toByte(), 0xE0.toByte(),
        0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01,
        0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00,
        0xFF.toByte(), 0xDB.toByte(), 0x00, 0x43, 0x00
    )

    private val DQT = byteArrayOf(
        0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08, 0x07,
        0x07, 0x07, 0x09, 0x09, 0x08, 0x0A, 0x0C, 0x14,
        0x0D, 0x0C, 0x0B, 0x0B, 0x0C, 0x19, 0x12, 0x13,
        0x0F, 0x14, 0x1D, 0x1A, 0x1F, 0x1E, 0x1D, 0x1A,
        0x1C, 0x1C, 0x20, 0x2E, 0x27, 0x20, 0x22, 0x2C,
        0x23, 0x1C, 0x1C, 0x28, 0x37, 0x29, 0x2C, 0x30,
        0x31, 0x34, 0x34, 0x34, 0x1F, 0x27, 0x39, 0x3D,
        0x38, 0x32, 0x3C, 0x2E, 0x33, 0x34, 0x32
    )

    private val SOF_BODY = byteArrayOf(
        0x00, 0x08, 0x00, 0x02, 0x00, 0x02, 0x03, 0x01,
        0x11, 0x00, 0x02, 0x11, 0x01, 0x03, 0x11, 0x01
    )

    private val SOS_BODY = byteArrayOf(0x03, 0x01, 0x00, 0x02, 0x11, 0x03, 0x11, 0x00, 0x3F, 0x00)

    fun bytes(): ByteArray {
        val sosHeader = byteArrayOf(
            0xFF.toByte(), 0xDA.toByte(),
            ((SOS_BODY.size shr 8) and 0xFF).toByte(),
            (SOS_BODY.size and 0xFF).toByte()
        )
        val ecs = ByteArray(12) { i -> if (i < 6) 0x55 else 0xAA.toByte() }
        val eoi = byteArrayOf(0xFF.toByte(), 0xD9.toByte())

        return HEADER + DQT +
            byteArrayOf(
                0xFF.toByte(), 0xC0.toByte(),
                ((SOF_BODY.size shr 8) and 0xFF).toByte(),
                (SOF_BODY.size and 0xFF).toByte()
            ) +
            SOF_BODY + sosHeader + SOS_BODY + ecs + eoi
    }
}
